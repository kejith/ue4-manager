const assert=require('node:assert/strict');
const fs=require('node:fs');
const vm=require('node:vm');
const ctx={localStorage:{getItem:()=>null,setItem:()=>{}},module:{exports:{}},Object,Number,Math,JSON,String,Array,RegExp};
vm.runInNewContext(fs.readFileSync('web/mines.js','utf8'),ctx,{filename:'web/mines.js'});
const {extract,evaluate,parseCosts,parseWeights}=ctx.module.exports;
assert.equal(parseCosts('ore:100, crystal:25').ore,100);
assert.equal(parseCosts('ore:100, crystal:25').crystal,25);
assert.equal(parseCosts('ore:nope'),null);
assert.equal(parseCosts('ore:-5'),null);
assert.equal(parseWeights('ore:1, crystal:2').crystal,2);
assert.equal(parseWeights('ore:0'),null);
const planets=[{id:1,name:'Alpha',resources:{ore:150,crystal:100},mines:{'Ore Mine':{level:5,productionPerHour:50,nextUpgrade:{cost:{ore:100,crystal:25},productionPerHour:60,buildTimeSeconds:7200}},'Crystal Mine':2},buildings:[{type:'Power Plant',level:4},{type:'Ore Mine',level:5}]}, {id:2,name:'Beta',mines:{'Ore Mine':{level:3}}}];
const mines=extract(planets);
assert.equal(mines.length,3,'Deduplicate mines/buildings and skip non-mining buildings');
assert.equal(mines[0].level,5);
assert.equal(mines[0].output,'ore');
assert.equal(mines[0].delta,10);
assert.equal(mines[0].buildHours,2);
const r=evaluate(mines[0],{},{});
assert.equal(r.valid,true);
assert.equal(r.affordable,true);
assert.equal(r.capex,125);
assert.equal(r.paybackHours,14.5);
assert.equal(r.roi30,100*((10*718)-125)/125);
const scaled=evaluate(mines[0],{}, {crystal:2});
assert.equal(scaled.capex,150);
assert.equal(scaled.paybackHours,17);
const down=evaluate(mines[0],{}, {},true);
assert.equal(down.paybackHours,24.5);
assert.equal(down.lost,100);
assert.equal(evaluate(mines[1],{},{}).valid,false,'Unknown upgrade costs must not be guessed');
const ref={buildings:[{name:'Crystal Mine',levels:[{level:3,cost:{ore:200},productionPerHour:14,buildTimeSeconds:3600}]}]};
const full=extract([{id:4,name:'Gamma',mines:{'Crystal Mine':{level:2,productionPerHour:10}}}],ref);
assert.equal(full[0].delta,4);
assert.equal(full[0].cost,'ore:200');
assert.equal(full[0].buildHours,1);
assert.equal(evaluate(full[0],{},{}).valid,true);
assert.equal(evaluate(full[0],{cost:'ore:500',delta:'20',hours:'3'},{}).paybackHours,28);
console.log('Mine planner calculations, extraction, and invalid-input checks passed');